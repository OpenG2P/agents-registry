"""The Agent register: the agents who serve farmers.

A conventional (entity) register, kept through change requests approved in AWE;
its version history is the audit trail of every assignment and status change.
The record's functional_record_id is the Agent ID, generated by the ID generator
(pool ``agent``, eight digits) when the intake form that registers the agent is
approved. Person fields (name, gender, date of birth, the national ID as
foundational_id) come from G2PPerson. The location (G2PGeo) is the agent's
**current assigned area**: a Master Data geography unit at any level, with its
ancestry in geo_code_hierarchy_json.

Coded fields name Master Data lists (AGENT_* in the country pack's agriculture
domain); the platform checks them there. Specializations and qualifications are
list sections, each its own register of rows (agent_specialization.py,
agent_qualification.py).
"""

from datetime import date

from openg2p_registry_core.models import (
    G2PGeo,
    G2PGeoHistory,
    G2PPerson,
    G2PPersonHistory,
    G2PRegister,
    G2PRegisterHistory,
)
from openg2p_registry_core.models.g2p_intake_form import G2PIntakeForm
from sqlalchemy import Date, String
from sqlalchemy.orm import Mapped, mapped_column

from ..services import G2PRegisterDomainServiceAgent


class G2PAgent:
    # Identity and contact (the national ID is G2PPerson.foundational_id)
    employee_number: Mapped[str] = mapped_column(String, nullable=True, index=True)  # the employer's HR number
    languages_spoken: Mapped[str] = mapped_column(String, nullable=True)
    mobile_number: Mapped[str] = mapped_column(String, nullable=True, index=True)
    alternate_phone: Mapped[str] = mapped_column(String, nullable=True)
    email: Mapped[str] = mapped_column(String, nullable=True)

    # Employment
    position: Mapped[str] = mapped_column(String, nullable=True, index=True)  # AGENT_POSITION
    employer_type: Mapped[str] = mapped_column(String, nullable=True)  # AGENT_EMPLOYER_TYPE
    employer_name: Mapped[str] = mapped_column(String, nullable=True)
    employment_type: Mapped[str] = mapped_column(String, nullable=True)  # AGENT_EMPLOYMENT_TYPE
    date_of_hire: Mapped[date] = mapped_column(Date, nullable=True)

    # Current assignment (the area is G2PGeo's geo_lowest_level_value_id)
    service_point_name: Mapped[str] = mapped_column(String, nullable=True)
    service_point_type: Mapped[str] = mapped_column(String, nullable=True)  # AGENT_SERVICE_POINT_TYPE
    assigned_since: Mapped[date] = mapped_column(Date, nullable=True)
    assignment_reason: Mapped[str] = mapped_column(String, nullable=True)  # AGENT_ASSIGNMENT_REASON

    # Service status
    service_status: Mapped[str] = mapped_column(String, nullable=True, index=True)  # AGENT_SERVICE_STATUS
    service_status_date: Mapped[date] = mapped_column(Date, nullable=True)
    service_status_reason: Mapped[str] = mapped_column(String, nullable=True)


# All Register classes should have the prefix G2PRegister
class G2PRegisterAgent(G2PRegister, G2PPerson, G2PGeo, G2PAgent):
    __tablename__ = "g2p_register_agents"

    def get_search_text_fields(self) -> str:
        return G2PRegisterDomainServiceAgent().construct_search_text(self.to_dict())

    def get_record_name_fields(self) -> str:
        return G2PRegisterDomainServiceAgent().construct_record_name(self.to_dict())


# All Register History classes should have the prefix G2PRegisterHistory
class G2PRegisterHistoryAgent(G2PRegisterHistory, G2PPersonHistory, G2PGeoHistory, G2PAgent):
    __tablename__ = "g2p_register_history_agents"


# All Intake Form classes should have the prefix G2PIntakeForm
class G2PIntakeFormAgent(G2PIntakeForm, G2PRegister, G2PPerson, G2PGeo, G2PAgent):
    __tablename__ = "g2p_intake_form_agents"

    def get_search_text_fields(self) -> str:
        return G2PRegisterDomainServiceAgent().construct_search_text(self.to_dict())

    def get_record_name_fields(self) -> str:
        return G2PRegisterDomainServiceAgent().construct_record_name(self.to_dict())
