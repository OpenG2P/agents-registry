#!/usr/bin/env python3
"""Generate the Agents Registry seed SQL from scripts/agents_definitions.py.

    python3 scripts/build_seed_sql.py          # write the SQL files
    python3 scripts/build_seed_sql.py --check  # fail if the committed SQL is stale

A developer tool: it is not part of any image and never runs in a deployment.
Production uses only the SQL it writes into the extension's meta_data/, which is
committed, copied into the db-seed image at build, and run by db-seed at install.
Change agents_definitions.py, run this, and commit both; CI runs --check so the
committed SQL can never drift from the definitions.

Every statement is an upsert, so db-seed can re-run on each helm upgrade.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import agents_definitions as d  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
META = ROOT / "agents-extension/src/openg2p_registry_agents_extension/meta_data"

JSON_NULL = object()  # a JSON null (the text 'null'), as the platform's metadata columns expect


def q(value, jsonb=False) -> str:
    if value is JSON_NULL:
        return "'null'"
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, (dict, list)):
        text = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
        return f"CAST({q(text)} AS JSONB)" if jsonb else q(text)
    return "'" + str(value).replace("'", "''") + "'"


def upsert(table: str, row: dict, conflict: str, jsonb=False, update=True, keep=()) -> str:
    """An upsert. ``keep``: columns set on insert only, never overwritten on a re-seed."""
    columns = ", ".join(f'"{c}"' for c in row)
    values = ", ".join(q(v, jsonb) for v in row.values())
    keys = {c.strip().strip('"') for c in conflict.split(",")} | set(keep)
    action = "DO NOTHING"
    if update:
        action = "DO UPDATE SET " + ", ".join(f'"{c}" = EXCLUDED."{c}"' for c in row if c not in keys)
    return f'INSERT INTO "public"."{table}" ({columns}) VALUES ({values})\n  ON CONFLICT ({conflict}) {action};\n'


HEADER = (
    "-- Generated by scripts/build_seed_sql.py from scripts/agents_definitions.py. Do not edit by hand:\n"
    "-- change the definitions, regenerate and commit both. Only this SQL is used in a deployment.\n\n"
)


def register_definitions_sql() -> str:
    out = [HEADER]
    for r in d.REGISTERS:
        row = {
            "register_id": r["register_id"],
            "register_mnemonic": r["register_mnemonic"],
            "register_subject": r["register_subject"],
            "register_description": r["register_description"],
            "master_register_id": r["master_register_id"],
            "register_rank": r["register_rank"],
            "functional_id_generation_required": r["functional_id_generation_required"],
            "register_purpose": r["register_purpose"],
            "program_id": None,
            "program_mnemonic": None,
            "register_icon": None,
            "has_image": False,
            "dedup_is_enabled": r["dedup_is_enabled"],
            "dedup_threshold_score": r["dedup_threshold_score"],
            "completion_score_required": False,
            "outgest_applicable": False,
            "requires_registrant_authentication": False,
            "registrant_authentication_validity_days": 730,
            "registrant_re_auth_warning_days_before": 30,
        }
        # requires_registrant_authentication is set on insert only: the platform's
        # VC-issuance bootstrap Job turns it on for the Agent register, and a
        # re-seed on upgrade must not turn it back off.
        out.append(upsert("g2p_register_definitions", row, '"register_id"',
                          keep=("requires_registrant_authentication",)))
    return "".join(out)


def _search_results(fields) -> list:
    return [{"field_name": f, "display_label": label, "order": i} for i, (f, label) in enumerate(fields, start=1)]


def agent_register_sql() -> str:
    out = [HEADER, "-- The Agent register's search, duplicate check, sections, tabs and intake form.\n\n"]

    filters = [{"field_name": f, "display_label": label, "filter_type": kind, "order": i,
                "allowed_operators": ["eq", "contains"]} for i, (f, label, kind) in enumerate(d.FILTERS, start=1)]
    filters.append({"field_name": "record_status", "display_label": "Record status", "filter_type": "dropdown",
                    "order": len(filters) + 1, "allowed_operators": ["eq", "in"],
                    "options_source": [{"value": v, "label": v} for v in ("ACTIVE", "INACTIVE", "ARCHIVED")]})
    out.append(upsert("g2p_register_schemas", {
        "register_id": d.AGENT, "deduplicate_schema": d.DEDUPLICATE,
        "search_result_schema": _search_results(d.SEARCH_RESULTS), "filter_schema": filters,
    }, '"register_id"'))
    for register_id, fields in d.SECTION_SEARCH_RESULTS.items():
        out.append(upsert("g2p_register_schemas", {
            "register_id": register_id, "deduplicate_schema": JSON_NULL,
            "search_result_schema": _search_results(fields), "filter_schema": JSON_NULL,
        }, '"register_id"'))
    out.append("\n")

    for s in d.SECTIONS:
        out.append(upsert("g2p_register_sections", {
            "register_id": d.AGENT,
            "section_id": s["section_id"],
            "section_register_id": s["section_register_id"],
            "is_core_section": False,
            "section_mnemonic": s["section_mnemonic"],
            "section_description": s["section_description"],
            "documents_required": False,
            "no_of_verifications_required": 0,
            "is_list": s["is_list"],
            "section_weightage": 10,
            "section_ui_schema": s["section_ui_schema"],
            "cr_auto_approve_for_bene_portal": False,
            "cr_auto_approve_for_agent_portal": False,
            "cr_auto_approve_for_staff_portal": False,
            "cr_auto_approve_for_partner": False,
        }, '"section_id"'))
    out.append("\n")

    for tab_id, label, order, sections in d.TABS:
        out.append(upsert("g2p_register_ui_tabs", {
            "tab_id": tab_id, "register_id": d.AGENT, "tab_label": label, "tab_order": order, "is_active": True,
        }, '"tab_id"'))
        for index, section_id in enumerate(sections, start=1):
            out.append(upsert("g2p_register_ui_tab_sections", {
                "tab_section_id": f"{tab_id}__{section_id}", "register_id": d.AGENT, "tab_id": tab_id,
                "section_id": section_id, "section_order": index * 10,
            }, '"tab_section_id"'))
    out.append("\n")

    intake = d.INTAKE
    out.append(upsert("g2p_intake_form_definitions", {
        "form_id": intake["form_id"], "register_id": d.AGENT, "form_mnemonic": intake["form_mnemonic"],
        "form_description": intake["form_description"], "number_of_verifications": 0,
        "used_only_in_ingestion_pipeline": False,
    }, '"form_id"'))
    out.append(upsert("g2p_intake_form_ui_tabs", {
        "tab_id": intake["tab_id"], "form_id": intake["form_id"], "tab_label": "New agent", "tab_order": 1,
    }, '"tab_id"'))
    for index, section_id in enumerate(intake["sections"], start=1):
        out.append(upsert("g2p_intake_form_ui_tab_sections", {
            "tab_section_id": f"{intake['tab_id']}__{section_id}", "tab_id": intake["tab_id"],
            "section_id": section_id, "section_order": index * 10,
        }, '"tab_section_id"'))
    return "".join(out)


def awe_policies_sql() -> str:
    out = [HEADER, "-- Agent change requests and the agent intake form are approved in AWE under these policy keys\n"
                   "-- (seeded into the shared AWE database by awe_meta_data/). AgentTraining has no change requests.\n"]
    for config_id, scope, form_id, policy_type, policy_key in d.AWE_POLICIES:
        out.append(upsert("g2p_registry_awe_policy_configurations", {
            "awe_policy_config_id": config_id, "policy_scope": scope, "register_id": d.AGENT,
            "intake_form_id": form_id, "section_id": "", "policy_type": policy_type, "policy_key": policy_key,
            "context_field_names": JSON_NULL,
        }, '"awe_policy_config_id"', update=False))
    return "".join(out)


def activity_types_sql() -> str:
    out = [HEADER]
    for index, t in enumerate(d.ACTIVITY_TYPES, start=1):
        row = {
            "activity_type_id": f"a6e00000-0000-4000-8000-0000000a01{index:02d}",
            "register_id": d.TRAINING,
            "activity_type": t["activity_type"],
            "display_name": t["display_name"],
            "description": t.get("description"),
            "display_order": t.get("display_order"),
            "is_active": True,
            "payload_schema": t["payload_schema"],
            "section_ui_schema": t.get("section_ui_schema"),
            "requires_context": t.get("requires_context", True),
            "is_repeatable": t.get("is_repeatable", True),
            "uniqueness_fields": t.get("uniqueness_fields"),
            "requires_prior_types": t.get("requires_prior_types"),
            "sequence_enforcement": t.get("sequence_enforcement", "WARN"),
            "due_rule": t.get("due_rule"),
            "max_backdate_days": t.get("max_backdate_days"),
            "allow_future_dated": t.get("allow_future_dated", False),
            "requires_verification": t.get("requires_verification", False),
            "reference_rules": t.get("reference_rules"),
            "ethiopian_date_fields": t.get("ethiopian_date_fields"),
            "participant_roles": {
                role: config for role, config in d.PARTICIPANT_ROLES.items()
                if config["field"] in t["payload_schema"]["properties"]
            },
        }
        out.append(upsert("g2p_activity_types", row, "register_id, activity_type", jsonb=True))
    return "".join(out)


def indicators_sql() -> str:
    out = [HEADER]
    for index, (code, name, unit, definition, order) in enumerate(d.INDICATORS, start=1):
        out.append(upsert("g2p_activity_indicators", {
            "indicator_id": f"a6e00000-0000-4000-8000-0000000a02{index:02d}", "register_id": d.TRAINING,
            "indicator_code": code, "display_name": name, "unit": unit, "definition": definition,
            "display_order": order, "is_active": True, "description": None,
        }, "register_id, indicator_code", jsonb=True))
    return "".join(out)


def outputs() -> dict[Path, str]:
    # No code lists: they live in Master Data (the country pack's agriculture
    # domain, AGENT_* lists) and the platform reads them there.
    return {
        META / "register-metadata/10_register_definitions.sql": register_definitions_sql(),
        META / "register-metadata/20_agent_register.sql": agent_register_sql(),
        META / "awe-integration/g2p_registry_awe_policy_configurations.sql": awe_policies_sql(),
        META / "activity-metadata/10_g2p_activity_types.sql": activity_types_sql(),
        META / "activity-metadata/20_g2p_activity_indicators.sql": indicators_sql(),
    }


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for path, content in outputs().items():
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Seed SQL is stale; run scripts/build_seed_sql.py:\n  " + "\n  ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
